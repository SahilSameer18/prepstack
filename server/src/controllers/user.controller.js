const userModel = require('../models/auth.model');
const projectModel = require('../models/project.model');
const progressModel = require('../models/progress.model');
const DSASheet = require('../models/sheets.model');
const AppError = require('../utils/AppError');
const bcrypt = require('bcrypt');

const formatUserResponse = (user) => {
  const dicebearAvatar = `https://api.dicebear.com/7.x/bottts/svg?seed=${encodeURIComponent(user.username)}`;
  
  return {
    id: user._id,
    username: user.username,
    email: user.email,
    avatar: user.avatar || dicebearAvatar,
    providers: user.providers || [],
    hasPassword: !!user.password,
    createdAt: user.createdAt
  };
};

// ── Get user stats ────────────────────────────────────────────────────────────

const getUserStats = async (req, res, next) => {
  try {
    const userId = req.user._id || req.user.id;

    // Count total projects generated by the user
    const generatedProjectsCount = await projectModel.countDocuments({ user: userId });

    // Aggregate total solved DSA problems from progress tracking
    const progressDocs = await progressModel.find({ user: userId });
    const solvedDSACount = progressDocs.reduce((total, doc) => {
      return total + (doc.solvedProblems ? doc.solvedProblems.length : 0);
    }, 0);

    res.status(200).json({
      success: true,
      stats: {
        generatedProjectsCount,
        solvedDSACount
      }
    });
  } catch (error) {
    next(error);
  }
};

// ── Get unified dashboard summary (single roundtrip server aggregator) ────────

const getDashboardSummary = async (req, res, next) => {
  try {
    const userId = req.user._id || req.user.id;

    // Parallel server queries: all DSA sheets, user's progress records, and project count
    const [sheets, userProgress, generatedProjectsCount] = await Promise.all([
      DSASheet.find({}, 'name slug description topics.problems.link topics.questions.link'),
      progressModel.find({ user: userId }),
      projectModel.countDocuments({ user: userId })
    ]);

    // Map user progress by sheetSlug for O(1) lookups
    const progressMap = new Map(
      userProgress.map((p) => [p.sheetSlug, p.solvedProblems || []])
    );

    let totalSolved = 0;
    let totalQuestions = 0;
    let sheetsInProgress = 0;
    let sheetsCompleted = 0;

    const dsaSheets = sheets.map((sheet) => {
      const linkSet = new Set();
      (sheet.topics || []).forEach((t) => {
        (t.problems || t.questions || []).forEach((p) => {
          if (p.link) linkSet.add(p.link);
        });
      });

      const total = linkSet.size;
      const solvedList = progressMap.get(sheet.slug) || [];
      const solved = solvedList.filter((link) => linkSet.has(link)).length;

      totalSolved += solved;
      totalQuestions += total;
      if (solved > 0 && solved < total) sheetsInProgress++;
      if (solved > 0 && total > 0 && solved >= total) sheetsCompleted++;

      return {
        sheet: {
          name: sheet.name,
          slug: sheet.slug,
          description: sheet.description || '',
        },
        solved,
        total,
      };
    });

    const overallPct =
      totalQuestions === 0
        ? 0
        : Math.round((totalSolved / totalQuestions) * 100);

    res.status(200).json({
      success: true,
      data: {
        stats: {
          totalSolved,
          totalQuestions,
          sheetsInProgress,
          sheetsCompleted,
          overallPct,
          generatedProjectsCount,
        },
        dsaSheets,
      },
    });
  } catch (error) {
    next(error);
  }
};

// ── Update user profile (username, avatar only — email is immutable) ───────────

const updateProfile = async (req, res, next) => {
  try {
    const userId = req.user._id || req.user.id;
    const { username, avatar } = req.body;

    const user = await userModel.findById(userId);
    if (!user) {
      return next(new AppError(404, 'User not found'));
    }

    // Check if username is being changed and is already taken by someone else (case-insensitive)
    if (username && username.trim() !== user.username) {
      const cleanUsername = username.trim();
      const existingUsername = await userModel.findOne({
        username: { $regex: new RegExp(`^${cleanUsername}$`, 'i') },
        _id: { $ne: userId }
      });
      if (existingUsername) {
        return next(new AppError(409, 'This username is already taken. Please choose a unique username.'));
      }
      user.username = cleanUsername;
    }

    if (avatar !== undefined) {
      user.avatar = avatar;
    }

    await user.save();

    res.status(200).json({
      success: true,
      message: 'Profile updated successfully',
      user: formatUserResponse(user)
    });
  } catch (error) {
    next(error);
  }
};

// ── Change user password ───────────────────────────────────────────────────────

const changePassword = async (req, res, next) => {
  try {
    const userId = req.user._id || req.user.id;
    const { currentPassword, newPassword } = req.body;

    const user = await userModel.findById(userId);
    if (!user) {
      return next(new AppError(404, 'User not found'));
    }

    if (!user.password) {
      return next(new AppError(400, 'This account is managed with Google Sign-In and does not have a password set. Please use "Set Password" first.'));
    }

    const isMatch = await bcrypt.compare(currentPassword, user.password);
    if (!isMatch) {
      return next(new AppError(401, 'Incorrect current password'));
    }

    const isSamePassword = await bcrypt.compare(newPassword, user.password);
    if (isSamePassword) {
      return next(new AppError(400, 'New password must be different from your current password'));
    }

    const hash = await bcrypt.hash(newPassword, 12);
    user.password = hash;
    await user.save();

    res.status(200).json({
      success: true,
      message: 'Password changed successfully',
      user: formatUserResponse(user)
    });
  } catch (error) {
    next(error);
  }
};

module.exports = { getUserStats, getDashboardSummary, updateProfile, changePassword };



