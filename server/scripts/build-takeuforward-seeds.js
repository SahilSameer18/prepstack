// Rebuilds the Striver A2Z and Striver SDE seed files from takeUforward's own pages (the old article links had all moved).
// Run: cd server && node scripts/build-takeuforward-seeds.js      (needs internet; writes the two seed files, never touches the database)
// Then seed as usual:  node src/modules/sheets/seeds/masterSeed.js
//
// What is copied from the page: module and problem names, the problem's practice page, its video lecture and its article.
// What is ours: the Easy / Medium / Hard label (the page has none). Labels live in seeds/ratings/<slug>.json, keyed by the problem's slug;
// edit a label there and run this script again. A problem with no entry there is labelled Medium.
const fs = require('node:fs');
const path = require('node:path');
const { extractRows, buildOutline, fetchSheetPage } = require('./lib/takeuforward');

const SEEDS = path.join(__dirname, '../src/modules/sheets/seeds');
const SHEETS = [
  {
    slug: 'striver-a2z', name: 'Striver A2Z DSA Sheet', url: 'https://takeuforward.org/prep-hub/strivers-a2z-dsa-sheet',
    file: 'striverA2ZSeed.js', variable: 'striverA2ZData', seedFunction: 'seedStriverA2Z', logName: 'Striver A2Z Sheet',
    description: "Striver's A2Z DSA course as problems, grouped by his modules. Each problem links to its takeUforward practice page, with his video lecture and article where he has one.",
  },
  {
    slug: 'striver-sde', name: 'Striver SDE Sheet', url: 'https://takeuforward.org/prep-hub/strivers-180-master-dsa-patterns', // takeUforward now calls the SDE sheet "Striver's 180"
    file: 'striverSDESeed.js', variable: 'striverSDEData', seedFunction: 'seedStriverSDE', logName: 'Striver SDE Sheet',
    description: "Striver's SDE sheet, which takeUforward now calls Striver's 180: problems grouped by pattern. Each problem links to its takeUforward practice page, with his video lecture and article where he has one.",
  },
];

const q = (value) => JSON.stringify(value);
const tagOf = (text) => String(text).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

function buildData(sheet, outline, ratings) {
  const seen = new Set();
  const topics = [];
  const used = new Set();
  for (const module of outline) {
    const problems = [];
    for (const section of module.sections) {
      for (const item of section.items) {
        if (item.kind !== 'practice' || seen.has(item.slug)) continue;
        seen.add(item.slug);
        const tags = [...new Set([tagOf(module.title), tagOf(section.title)])].filter(Boolean).slice(0, 2);
        problems.push({
          title: item.title, link: item.practiceUrl, difficulty: ratings[item.slug] || 'Medium', tags,
          ...(item.video ? { video: item.video } : {}), ...(item.article ? { article: item.article } : {}),
        });
      }
    }
    if (!problems.length) continue;
    let id = tagOf(module.slug || module.title);
    while (used.has(id)) id += '-2';
    used.add(id);
    topics.push({ id, title: module.title.trim(), problems });
  }
  return { name: sheet.name, slug: sheet.slug, description: sheet.description, topics };
}

function render(sheet, data) {
  const problem = (p) => `        { title: ${q(p.title)}, link: ${q(p.link)}, difficulty: ${q(p.difficulty)}, tags: ${q(p.tags)}${p.video ? `, video: ${q(p.video)}` : ''}${p.article ? `, article: ${q(p.article)}` : ''} },`;
  const topic = (t) => `    {\n      id: ${q(t.id)},\n      title: ${q(t.title)},\n      problems: [\n${t.problems.map(problem).join('\n')}\n      ]\n    },`;
  return `// Generated by scripts/build-takeuforward-seeds.js from ${sheet.url}. Edit the Easy/Medium/Hard labels in seeds/ratings/${sheet.slug}.json, then run the script again.
const DSASheet = require('../../sheets.model');
const connectDB = require('../../../../shared/config/seedConfig');

const ${sheet.variable} = {
  name: ${q(data.name)},
  slug: ${q(data.slug)},
  description: ${q(data.description)},
  topics: [
${data.topics.map(topic).join('\n')}
  ]
};

const ${sheet.seedFunction} = async () => {
  await connectDB();
  await DSASheet.findOneAndUpdate(
    { slug: ${sheet.variable}.slug },
    ${sheet.variable},
    { upsert: true, returnDocument: 'after' }
  );
  console.log('${sheet.logName} Seeded');
};

module.exports = ${sheet.seedFunction};
module.exports.data = ${sheet.variable};
`;
}

(async () => {
  for (const sheet of SHEETS) {
    const outline = buildOutline(extractRows(await fetchSheetPage(sheet.url)));
    const ratings = JSON.parse(fs.readFileSync(path.join(SEEDS, 'ratings', `${sheet.slug}.json`), 'utf8'));
    const data = buildData(sheet, outline, ratings);
    const count = data.topics.reduce((n, t) => n + t.problems.length, 0);
    const withVideo = data.topics.reduce((n, t) => n + t.problems.filter((p) => p.video).length, 0);
    const withArticle = data.topics.reduce((n, t) => n + t.problems.filter((p) => p.article).length, 0);
    fs.writeFileSync(path.join(SEEDS, 'sheetSeeds', sheet.file), render(sheet, data));
    console.log(`${sheet.slug}: ${data.topics.length} topics, ${count} problems, ${withVideo} with a video, ${withArticle} with an article`);
  }
})().catch((error) => { console.error(error.message); process.exit(1); });
